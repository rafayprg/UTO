import assert from "node:assert/strict";
import { formatJson, wifiPayload, youtubeId, cleanCaptions, textStatistics, calculatePercentage, convertUnit, httpUrl } from "../src/lib/native-tools.ts";
import { inspectZipSafety, uniqueArchiveNames } from "../src/lib/file-zip-safety.ts";
import JSZip from "jszip";
assert.deepEqual(JSON.parse(formatJson('{"a":[true,null,3]}',4)),{a:[true,null,3]});
assert.throws(()=>formatJson('{"a":1,}'));
assert.equal(formatJson('false',0),'false');
assert.throws(()=>formatJson(''));
assert.equal(wifiPayload('Office;2','a:b\\c','WPA',true),'WIFI:T:WPA;S:Office\\;2;P:a\\:b\\\\c;H:true;;');
assert.throws(()=>wifiPayload('a'.repeat(33),'x','WPA',false));
assert.throws(()=>httpUrl('javascript:alert(1)'));
assert.throws(()=>httpUrl('https://user:secret@example.com'));
assert.equal(youtubeId('https://youtu.be/dQw4w9WgXcQ?t=4'),'dQw4w9WgXcQ');
assert.equal(youtubeId('https://www.youtube.com/shorts/dQw4w9WgXcQ'),'dQw4w9WgXcQ');
assert.throws(()=>youtubeId('https://youtube.com.evil.example/watch?v=dQw4w9WgXcQ'));
const captions='1\n00:00:01,000 --> 00:00:02,000\n<b>Hello &amp; welcome.</b>\n\n2\n00:00:03,000 --> 00:00:04,000\n2026\n\n3\n00:00:05,000 --> 00:00:06,000\n2026';
assert.equal(cleanCaptions(captions,true,false),'Hello & welcome.\n2026');
assert.equal(cleanCaptions('WEBVTT\n\nintro\n00:01.000 --> 00:02.000 align:start\nHello',true,false),'Hello');
assert.equal(textStatistics('👨‍👩‍👧‍👦').characters,1);
assert.equal(textStatistics('').words,0);
assert.equal(textStatistics('Hello world.').words,2);
assert.equal(calculatePercentage('of',20,150).result,30);
assert.equal(calculatePercentage('margin',60,100).result,40);
assert.equal(calculatePercentage('margin',0,100).markup,null);
assert.throws(()=>calculatePercentage('change',0,100));
assert.throws(()=>calculatePercentage('ratio',1,0));
assert.equal(convertUnit('data',1,'GiB','B'),1073741824);
assert.equal(convertUnit('data',8,'bit','B'),1);
assert(Math.abs(convertUnit('temperature',32,'F','C'))<1e-10);
assert.equal(convertUnit('temperature',-273.15,'C','K'),0);
assert.throws(()=>convertUnit('temperature',-1,'K','C'));
assert.throws(()=>convertUnit('mass',1,'kg','m'));
assert.deepEqual(uniqueArchiveNames(['x.txt','x.txt','X.txt']),['x.txt','x (2).txt','X (3).txt']);
